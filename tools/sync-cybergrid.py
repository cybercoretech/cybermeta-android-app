#!/usr/bin/env python3
"""Generate Palettes.kt from the CYBERGRID themes in the cybercore framework
repo (the source of truth), so the app's theme picker matches every other
Cybercore tool.

    tools/sync-cybergrid.py [path/to/cybercore]

Don't edit Palettes.kt by hand: change the themes in cybercore and re-run.
"""
import json
import pathlib
import sys

here = pathlib.Path(__file__).resolve().parent.parent
src = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else here / "../../Cybercore/framework/cybercore").resolve() / "schema/themes"
if not src.is_dir():
    sys.exit(f"no themes at {src}")
out = here / "app/src/main/java/dev/cybercore/cybermeta/Palettes.kt"
keys = ["bg", "panel", "line", "white", "muted", "cyan", "hot_pink", "purple", "acid_green", "orange", "red"]

def title(slug: str) -> str:
    return " ".join(w.capitalize() for w in slug.replace("_", "-").split("-"))

lines = [
    "// Generated by tools/sync-cybergrid.py from cybercore schema/themes. Don't edit.",
    "package dev.cybercore.cybermeta",
    "",
    "/** Every CYBERGRID palette, grouped by family, plus the cybermeta brand. */",
    "val PaletteFamilies: List<Pair<String, List<Palette>>> = listOf(",
    '    "Cybermeta" to listOf(TagRedact),',
]
count = 0
for family in sorted(p for p in src.iterdir() if p.is_dir()):
    entries = []
    for f in sorted(family.glob("*.json")):
        t = json.loads(f.read_text())
        missing = [k for k in keys if k not in t]
        if missing:
            sys.exit(f"{f}: missing {missing}")
        args = ", ".join(f"0xFF{t[k].lstrip('#').upper()}" for k in keys)
        entries.append(f'        Palette("{f.stem}", "{title(f.stem)}", {args}),')
        count += 1
    lines.append(f'    "{title(family.name)}" to listOf(')
    lines.extend(entries)
    lines.append("    ),")
lines.append(")")
out.write_text("\n".join(lines) + "\n")
print(f"wrote {count} palettes to {out.relative_to(here)}")
